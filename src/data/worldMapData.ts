// Helper to test if a coordinate is within a continent polygon
function isPointInPoly(lat: number, lon: number, poly: LatLon[]): boolean {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const xi = poly[i][1], yi = poly[i][0];
    const xj = poly[j][1], yj = poly[j][0];
    const intersect = ((yi > lat) !== (yj > lat)) &&
        (lon < (xj - xi) * (lat - yi) / (yj - yi) + xi);
    if (intersect) inside = !inside;
  }
  return inside;
}

// Generate comprehensive dense land matrix covering all continents
function buildLandGrid(): LatLon[] {
  const points: LatLon[] = [...LANDMASS_MICRO_GRID];
  for (let lat = -55; lat <= 72; lat += 3.5) {
    for (let lon = -180; lon < 180; lon += 3.5) {
      for (const poly of WORLD_COASTLINES) {
        if (isPointInPoly(lat, lon, poly)) {
          points.push([Math.round(lat * 10) / 10, Math.round(lon * 10) / 10]);
          break;
        }
      }
    }
  }
  return points;
}

export const GENERATED_LAND_GRID: LatLon[] = buildLandGrid();

// Identify the closest continent or ocean region for any given (lat, lon) coordinate
export function getGeographicRegion(lat: number, lon: number): string {
  if (lat > 66.5) return 'Arctic Polar Basin';
  if (lat < -60) return 'Antarctic Ice Sheet';

  // Indian Subcontinent & Indian Ocean
  if (lat >= 5 && lat <= 37 && lon >= 68 && lon <= 92) {
    if (lat >= 8 && lat <= 35 && lon >= 69 && lon <= 89) return 'Indian Subcontinent';
    return 'Arabian Sea / Bay of Bengal';
  }
  if (lat >= -40 && lat <= 15 && lon >= 50 && lon <= 100) return 'Indian Ocean Basin';

  // East & Southeast Asia
  if (lat >= 15 && lat <= 55 && lon >= 95 && lon <= 145) return 'East Asian Region';
  if (lat >= -10 && lat <= 20 && lon >= 95 && lon <= 140) return 'Southeast Asia & Sundaland';

  // Europe & Mediterranean
  if (lat >= 35 && lat <= 70 && lon >= -10 && lon <= 45) {
    if (lat <= 45 && lon >= 0 && lon <= 35) return 'Mediterranean Basin';
    return 'European Continent';
  }

  // Middle East & Central Asia
  if (lat >= 12 && lat <= 45 && lon >= 35 && lon <= 70) return 'Middle East & Central Asia';

  // Africa
  if (lat >= -35 && lat <= 37 && lon >= -20 && lon <= 55) {
    if (lat >= 15) return 'Sahara / North Africa';
    if (lat >= -5 && lat < 15) return 'Sub-Saharan & Central Africa';
    return 'Southern African Basin';
  }

  // North America
  if (lat >= 15 && lat <= 70 && lon >= -170 && lon <= -50) {
    if (lat >= 50) return 'Canadian Shield & Boreal Forest';
    if (lat <= 25) return 'Central America & Caribbean';
    return 'North American Continent';
  }

  // South America
  if (lat >= -60 && lat <= 15 && lon >= -85 && lon <= -30) {
    if (lat >= -15 && lat <= 5 && lon >= -75 && lon <= -50) return 'Amazon Biosphere Basin';
    return 'South American Continent';
  }

  // Oceania
  if (lat >= -50 && lat <= 0 && lon >= 110 && lon <= 180) {
    if (lat <= -10 && lon >= 112 && lon <= 155) return 'Australian Continent';
    return 'South Pacific & Oceania';
  }

  // Oceans
  if (lon >= -70 && lon <= 20) return 'Atlantic Ocean Basin';
  return 'Pacific Ocean Basin';
}

